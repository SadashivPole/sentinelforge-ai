# ---------------------------------------------------------------------------
# Calculate metrics per rule
# ---------------------------------------------------------------------------

# Build lookup: event_id -> ground truth
gt_lookup = {g["event_id"]: g for g in holdout_ground_truth}

# Build lookup: event_id -> detection results that cite it
detection_citations: dict[str, list[DetectionResult]] = {}
for r in detection_results:
    for ev in r.evidence:
        detection_citations.setdefault(ev.event_id, []).append(r)

# Per-rule metrics — match by rule_id
rule_configs = [
    ("sentinelforge.detection.failed_login_burst", "FailedLoginBurstRule", "failed_login_burst"),
    ("sentinelforge.detection.password_spray", "PasswordSprayRule", "password_spray"),
    ("sentinelforge.detection.suspicious_powershell", "SuspiciousPowerShellRule", "powershell"),
    ("sentinelforge.detection.suspicious_processtree", "SuspiciousProcessTreeRule", "suspicious_processtree"),
    ("sentinelforge.detection.c2_beacon", "C2BeaconRule", "c2_beacon"),
]

print("\n" + "=" * 80)
print("HOLDOUT DETECTION QUALITY METRICS")
print("=" * 80)

for rule_id, rule_name, category in rule_configs:
    rule_dets = [r for r in detection_results if r.rule_id == rule_id]

    # Detected event IDs for this rule
    detected_ids = set()
    for r in rule_dets:
        for ev in r.evidence:
            detected_ids.add(ev.event_id)

    # Ground truth events for this category
    gt_for_category = [g for g in holdout_ground_truth if g["expected_category"] == category]
    gt_ids = {g["event_id"] for g in gt_for_category}

    # All suspicious ground truth events
    all_suspicious_ids = {g["event_id"] for g in holdout_ground_truth if g["is_suspicious"]}
    all_benign_ids = {g["event_id"] for g in holdout_ground_truth if not g["is_suspicious"]}

    # True positives: detected events that are suspicious AND match this category
    true_positives = detected_ids & gt_ids
    # False positives: detected events that are benign
    false_positives = detected_ids & all_benign_ids
    # False negatives: suspicious events for this category NOT detected
    false_negatives = gt_ids - detected_ids
    # Unassessed: detected events not in ground truth at all
    unassessed = detected_ids - (all_suspicious_ids | all_benign_ids)

    tp = len(true_positives)
    fp = len(false_positives)
    fn = len(false_negatives)
    unassessed_count = len(unassessed)

    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0

    print(f"\n--- {rule_name} ({category}) ---")
    print(f"  Ground truth events: {len(gt_ids)}")
    print(f"  Detected events: {len(detected_ids)}")
    print(f"  True Positives: {tp}")
    print(f"  False Positives: {fp}")
    print(f"  False Negatives: {fn}")
    print(f"  Unassessed alerts: {unassessed_count}")
    print(f"  Precision: {precision:.4f} ({tp}/{tp+fp})")
    print(f"  Recall: {recall:.4f} ({tp}/{tp+fn})")
    print(f"  F1: {f1:.4f}")

    if false_positives:
        print(f"  FP event IDs: {sorted(false_positives)}")
    if false_negatives:
        print(f"  FN event IDs: {sorted(false_negatives)}")
    if unassessed:
        print(f"  Unassessed event IDs: {sorted(unassessed)}")

# ---------------------------------------------------------------------------
# Overall metrics
# ---------------------------------------------------------------------------
print("\n" + "=" * 80)
print("OVERALL HOLDOUT METRICS")
print("=" * 80)

all_detected = set()
for r in detection_results:
    for ev in r.evidence:
        all_detected.add(ev.event_id)

all_tp = all_detected & all_suspicious_ids
all_fp = all_detected & all_benign_ids
all_fn = all_suspicious_ids - all_detected

overall_precision = len(all_tp) / (len(all_tp) + len(all_fp)) if (len(all_tp) + len(all_fp)) > 0 else 0.0
overall_recall = len(all_tp) / (len(all_tp) + len(all_fn)) if (len(all_tp) + len(all_fn)) > 0 else 0.0
overall_f1 = 2 * overall_precision * overall_recall / (overall_precision + overall_recall) if (overall_precision + overall_recall) > 0 else 0.0

print(f"Total suspicious (GT): {len(all_suspicious_ids)}")
print(f"Total benign (GT): {len(all_benign_ids)}")
print(f"Total detected: {len(all_detected)}")
print(f"Overall True Positives: {len(all_tp)}")
print(f"Overall False Positives: {len(all_fp)}")
print(f"Overall False Negatives: {len(all_fn)}")
print(f"Overall Precision: {overall_precision:.4f}")
print(f"Overall Recall: {overall_recall:.4f}")
print(f"Overall F1: {overall_f1:.4f}")
print("=" * 80)