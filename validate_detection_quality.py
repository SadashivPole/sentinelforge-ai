"""SentinelForge AI — Independent Detection Quality Validation (Phase 2, Item 6).

Creates an independently authored holdout dataset NOT generated by the same
scenario code used by detection rules. This prevents circular assumptions
where detectors and test data encode the same assumptions.

The holdout dataset includes:
- True malicious patterns (password spraying, brute force, C2 beaconing,
  suspicious process trees, suspicious PowerShell)
- Benign administrative activity
- Legitimate PowerShell usage
- Benign encoded commands
- Authentication failures that do NOT represent spraying
- Legitimate periodic network traffic
- Suspicious beacon-like traffic
- Process-tree scenarios with ambiguous evidence
- Incomplete and noisy records

For every detection rule, calculates:
- True positives, false positives, false negatives
- Unassessed alerts
- Precision, recall
- F1 only where numerator/denominator units genuinely match

Never tunes thresholds using the final holdout dataset.
"""

