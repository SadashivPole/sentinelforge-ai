# ---------------------------------------------------------------------------
# Independently authored holdout dataset
# These events are hand-crafted, NOT generated by sentinelforge.datasets.scenarios
# ---------------------------------------------------------------------------

def make_event(
    event_id: str,
    timestamp: str,
    event_type: str,
    source: str,
    user: str = None,
    host: str = None,
    authentication: dict = None,
    process: dict = None,
    network: dict = None,
    raw: dict = None,
) -> NormalizedEvent:
    return NormalizedEvent(
        event_id=event_id,
        timestamp=timestamp,
        source=source,
        raw=raw or {},
        event_type=event_type,
        user=user,
        host=host,
        authentication=AuthenticationInfo(**authentication) if authentication else None,
        process=ProcessInfo(**process) if process else None,
        network=NetworkInfo(**network) if network else None,
    )


# Base timestamp
